export const CANONICAL_CURRICULUM_MANIFEST: Record<string, SubjectCurriculumMetadata> = Object.fromEntries(
  CANONICAL_50_SUBJECTS.map((s) => [
    s.code,
    {
      code: s.code,
      vertical: s.vertical,
      electiveGroup: s.electiveGroup,
      electiveOption: s.electiveOption,
      sourcePdf: s.sourcePdf,
      sourcePage: s.sourcePage,
      acResolution: s.acResolution,
      isVerified: s.isVerified,
      isManifestMatched: s.isManifestMatched,
    },
  ])
);

/**
 * Hydrates any database Subject record with its canonical curriculum metadata.
 * 
 * Epistemic Fallback Contract:
 * - Verified manifest entries receive full NEP vertical, PDF citation, and academic resolutions.
 * - Non-manifest subjects (including the 7 prototype baseline records) return strictly null
 *   for vertical, elective options, and source citations, with isVerified: false and isManifestMatched: false.
 */
export function enrichSubject<T extends { code: string }>(
  subject: T
): T & { metadata: SubjectCurriculumMetadata } {
  const match = CANONICAL_CURRICULUM_MANIFEST[subject.code];

  if (match) {
    return {
      ...subject,
      metadata: {
        ...match,
        isVerified: true,
        isManifestMatched: true,
      },
    };
  }

  // Strictly null unclassified state - zero speculative defaults
  return {
    ...subject,
    metadata: {
      code: subject.code,
      vertical: null,
      electiveGroup: null,
      electiveOption: null,
      sourcePdf: null,
      sourcePage: null,
      acResolution: null,
      isVerified: false,
      isManifestMatched: false,
    },
  };
}
